"""Generate board-local motor/app defaults from the archived user XML files."""
from pathlib import Path
import re
import xml.etree.ElementTree as E
root=Path(__file__).resolve().parent
source=(root.parents[1]/'confgenerator.c').read_text()
lines=['/* Generated by generate_stock_defaults.py from archived XML defaults. */','#ifndef SPEEDPED_STOCK_DEFAULTS_H','#define SPEEDPED_STOCK_DEFAULTS_H']
count=0
for filename in ('vesc_mcconf.xml','vesc_appconf.xml'):
    tree=E.parse(root/'defaults'/filename).getroot()
    assert tree.findtext('ConfigVersion')=='4'
    for element in tree:
        if element.tag=='ConfigVersion': continue
        name=re.sub(r'__(\d+)',r'[\1]',element.tag)
        match=re.search(r'conf->'+re.escape(name)+r' = ([A-Z][A-Z0-9_]+);',source)
        if not match:
            assert element.tag.startswith('motor_') and element.tag!='motor_type',element.tag
            continue # Tool-only descriptive metadata, not part of mc_configuration.
        macro='APPCONF_CONTROLLER_ID' if name=='controller_id' else match[1]
        assert re.fullmatch(r'[-+0-9.eE]+',element.text or '')
        lines.extend([f'#undef {macro}',f'#define {macro} ({element.text})'])
        count+=1
lines.append('#endif')
(root/'stock_defaults.h').write_text('\n'.join(lines)+'\n')
print(f'Generated {count} motor/app defaults.')
