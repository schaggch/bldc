"""Generate the VESC custom-config schema and compressed firmware payload."""
from pathlib import Path
import xml.etree.ElementTree as E
import zlib, struct
root=Path(__file__).resolve().parent
fields=[
 ('wheel_mm','Radumfang',2100,100,5000,' mm','Radumfang am Reifen messen.'),
 ('wheel_pulses','Signale pro Radumdrehung',1,1,64,'','Fallende Flanken am Hall-C-Eingang. Active low.'),
 ('pedal_kmh','maxSpeed pedaling',0,0,150,' km/h','0 = keine Geschwindigkeitsbegrenzung. PAS-Freigabe bleibt erforderlich. Im Duty-Modus Reduktion ab 80% bis null am Limit.'),
 ('ah_kmh','maxSpeed AH',0,0,30,' km/h','0 = keine Geschwindigkeitsbegrenzung. Hall A und B muessen gehalten werden; Leistung vom Gasgriff. Im Duty-Modus Reduktion ab 80%.'),
 ('pas_timeout','PAS Timeout',1000,50,5000,' ms','Maximales Alter einer gueltigen Pedalperiode.'),
 ('pas_magnets','Magnets per Round',5,1,64,'','Magnete pro Kurbelumdrehung, fuer die Trittfrequenz.'),
 ('pas_start','Min signals for start',2,1,32,'','Anzahl vollstaendiger gueltiger Perioden nach der Synchronisationsflanke.'),
 ('pas_duty','PAS Low-Anteil',1,0,1,'','Zeitanteil auf GND. Genau 50% wird nie als vorwaerts gewertet.'),
 ('no_wheel_seconds','Timeout ohne Radimpulse',5,0,120,' s','Zeit seit letzter Radflanke bzw. Start. 0 s deaktiviert die Ersatzbegrenzung ohne Radsignal, auch wenn eine eRPM-Grenze eingestellt ist.'),
 ('no_wheel_watts','Leistungsschwelle ohne Radsignal',0,0,100000,' W','Positive elektrische Batterie-Eingangsleistung. Oberhalb dieser Schwelle wird nach dem Timeout die Ersatzgrenze aktiviert.'),
 ('no_wheel_erpm','eRPM-Grenze ohne Radsignal',0,0,100000,' eRPM','0 deaktiviert die Ersatzbegrenzung. Nach Ausloesen bleibt sie bis zu einer gueltigen Radperiode aktiv, auch wenn die Leistung sinkt. Keine automatische Bremsung.'),
 ('sh_duty','maxDuty SH',0,0,95,' %','Duty-Modus: maximaler Tastgrad bei gehaltener SH. Gasgriff bestimmt die Anforderung. Ab 80% dieser Grenze steigt Duty langsamer; die Grenze wird nie ueberschritten. 0 sperrt SH im Duty-Modus. Keine feste Fahrgeschwindigkeit.')]
fields += [
 ('sound_start','Startton',0,0,1,'','0 = aus, 1 = kurzer Retro-Startton im Stillstand.'),
 ('sound_ride','Fahrmelodie',0,0,1,'','0 = aus, 1 = Retro-Melodie bei Fahrt und gueltigem PAS.'),
 ('sound_volume','Lautstaerke',10,0,100,' %','0 = stumm. Motorspezifische Spannungsgrenze noch zu validieren.'),
 ('sound_tempo','Tempo relativ zu PAS',100,25,400,' %','100% = eine Note pro Magnetperiode. 200% = doppelte Notenrate.')]
stock=E.parse(root/'defaults/vesc_Speedpedconf.xml').getroot()
fields=[(n,l,int(stock.findtext(n)),lo,hi,s,d) for n,l,default,lo,hi,s,d in fields]
(root/'bike_defaults.h').write_text('/* Generated stock SPEEDPED values. */\n#define SPEEDPED_BIKE_DEFAULT_VALUES '+','.join(str(f[2]) for f in fields)+'\n')
xml=E.Element('ConfigParams'); params=E.SubElement(xml,'Params')
def item(parent,name,value): E.SubElement(parent,name).text=str(value)
meta=E.SubElement(params,'hw_name'); item(meta,'type',0); item(meta,'longName','SPEEDPED'); item(meta,'transmittable',0)
meta=E.SubElement(params,'config_name'); item(meta,'type',3); item(meta,'valString','speedped_bike_v1'); item(meta,'transmittable',0)
sig=''
for name,label,default,lo,hi,suffix,desc in fields:
    p=E.SubElement(params,name); enum=name=='pas_duty'; typ=4 if enum else 2; tx=0 if enum else 6
    for k,v in [('type',typ),('vTx',tx),('longName',label),('description',desc),('transmittable',1),('valInt',default),('minInt',lo),('maxInt',hi),('stepInt',1),('suffix',suffix),('editorScale',1)]: item(p,k,v)
    sig+=name+str(typ)+str(tx)
    if enum:
        for label in ['Low < 50 %','Low > 50 %']: item(p,'enumNames',label); sig+=label
order=E.SubElement(xml,'SerOrder')
for f in fields: item(order,'ser',f[0])
g=E.SubElement(E.SubElement(xml,'Grouping'),'group'); item(g,'groupName','General')
for title,groupfields in [('Speed',fields[:4]+fields[8:12]),('PAS',fields[4:8]),('Sound',fields[12:])]:
    sub=E.SubElement(g,'subgroup'); item(sub,'subgroupName',title); ps=E.SubElement(sub,'subgroupParams')
    for f in groupfields: item(ps,'param',f[0])
E.indent(xml); data=E.tostring(xml,encoding='utf-8',xml_declaration=True)
(root/'bike.xml').write_bytes(data)
crc=0xffffffff
for b in sig.encode():
    crc^=b
    for _ in range(8): crc=(crc>>1)^(0x82f63b78 if crc&1 else 0)
crc^=0xffffffff
payload=struct.pack('>I',len(data))+zlib.compress(data,9)
(root/'bike_schema.h').write_text('/* Generated by generate_bike_schema.py */\n#define BIKE_SIGNATURE 0x%08xU\n#define BIKE_WIRE_SIZE 65U\nstatic const unsigned char bike_xml[] = {\n'%crc + ',\n'.join(','.join(str(b) for b in payload[i:i+24]) for i in range(0,len(payload),24))+'\n};\n')
print('Bike schema signature:',hex(crc),'compressed bytes:',len(payload))
